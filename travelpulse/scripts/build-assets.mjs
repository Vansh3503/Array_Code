#!/usr/bin/env node
// Embeds public/ into the Worker bundle (src/assets.gen.ts) so the dashboard ships
// inside the Worker itself: one deployment, no separate static-asset upload.
// Runs automatically before `wrangler dev` / `wrangler deploy` via [build] in wrangler.toml.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, extname, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pub = join(root, "public");
const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "application/javascript; charset=utf-8",
  ".png": "image/png",
  ".svg": "image/svg+xml",
  ".ico": "image/x-icon",
};

const files = {};
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (TYPES[extname(p)]) {
      files["/" + relative(pub, p).split("\\").join("/")] = { type: TYPES[extname(p)], b64: readFileSync(p).toString("base64") };
    }
  }
})(pub);

writeFileSync(
  join(root, "src", "assets.gen.ts"),
  `// AUTO-GENERATED by scripts/build-assets.mjs — do not edit.\n` +
    `export const ASSETS: Record<string, { type: string; b64: string }> = ${JSON.stringify(files)};\n`,
);
console.log(`embedded ${Object.keys(files).length} files from public/`);
